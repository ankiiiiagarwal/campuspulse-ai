export type I18nKey = keyof typeof EN;

function readLang(): Lang {
  if (typeof window === "undefined") return "en";
  return window.localStorage.getItem(STORAGE) === "hi" ? "hi" : "en";
}

export function speechLang(lang: Lang): string {
  return lang === "hi" ? "hi-IN" : "en-IN";
}

export function useLang() {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    setLangState(readLang());
    const onChange = () => setLangState(readLang());
    window.addEventListener(EVENT, onChange);
    return () => window.removeEventListener(EVENT, onChange);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang === "hi" ? "hi" : "en";
  }, [lang]);

  function setLang(next: Lang) {
    window.localStorage.setItem(STORAGE, next);
    setLangState(next);
    window.dispatchEvent(new Event(EVENT));
  }

  function t(key: I18nKey, vars?: Record<string, string>): string {
    const table = lang === "hi" ? HI : EN;
    let text: string = table[key] || EN[key];
    if (vars) {
      for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, v);
    }
    return text;
  }

  return { lang, setLang, t };
}
